const {Pool,types}=require('pg');
const {AsyncLocalStorage}=require('node:async_hooks');

const columns={deliveries:'id,received_at,payload',customer_accounts:'account_id,customer_id',
 customer_rules:'id,customer_id,account_id,keyword,reply,enabled',customer_sessions:'session_hash,customer_id,expires_at',
 customer_login_limits:'key,attempts,expires_at',customer_action_tokens:'token_hash,customer_id,purpose,expires_at',
 customer_mail_limits:'key,attempts,expires_at',subscription_usage:'draft_id,period_id,attempted_at',
 automation_account_runs:'account_id,last_run_at,status',service_probe:'id'};

// SQL is authored in the application, never supplied by clients. Keep its small
// portable statement dialect while PostgreSQL owns transactions/concurrency.
function postgresSql(input){
 let sql=input.replace(/PRAGMA\s+[^;]+;/gi,'');
 sql=sql.replace(/INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT/gi,'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
  .replace(/\bINTEGER\b/g,'BIGINT').replace(/\browid\b/gi,'ordinal');
 for(const table of ['customer_accounts','customer_rules'])
  sql=sql.replace(new RegExp('(CREATE TABLE IF NOT EXISTS '+table+'\\s*\\()','gi'),'$1 ordinal BIGSERIAL,');
 let ignored=/INSERT OR IGNORE INTO/i.test(sql);sql=sql.replace(/INSERT OR IGNORE INTO/gi,'INSERT INTO');
 sql=sql.replace(/INSERT INTO\s+(\w+)\s+VALUES/gi,(match,table)=>{
  if(!columns[table])throw new Error('Explicit insert columns required');
  return 'INSERT INTO '+table+' ('+columns[table]+') VALUES';
 });
 const target=/INSERT INTO\s+(\w+)/i.exec(sql)?.[1];
 if(target)sql=sql.replace(/SET attempts=attempts\+1/g,'SET attempts='+target+'.attempts+1');
 if(ignored)sql=sql.replace(/;?\s*$/,' ON CONFLICT DO NOTHING');
 // Number placeholders without changing question marks inside string literals.
 let output='',quoted=false,index=0;
 for(let i=0;i<sql.length;i++){
  const c=sql[i];
  if(c==="'"){
   output+=c;
   if(quoted&&sql[i+1]==="'"){output+=sql[++i];continue;}
   quoted=!quoted;continue;
  }
  output+=c==='?'&&!quoted?'$'+(++index):c;
 }
 return output;
}

class PostgresDatabase {
 constructor({connectionString,schema='vetastart_pilot',ssl,max=8}){
  if(!connectionString||!/^vetastart_[a-z0-9_]{1,32}$/.test(schema))throw new Error('Invalid PostgreSQL configuration');
  this.schema=schema;this.context=new AsyncLocalStorage();this.ddl=new Set();
  this.pool=new Pool({connectionString,ssl,max,connectionTimeoutMillis:5000,statement_timeout:15000,
   options:'-c search_path='+schema+',pg_catalog',types:{getTypeParser(oid,format){
    if(oid===20)return value=>{const number=Number(value);if(!Number.isSafeInteger(number))throw new Error('Unsafe database integer');return number;};
    return types.getTypeParser(oid,format);
   }}});
  this.pool.on('error',()=>{});
 }
 async initialize(){
  const db=await this.pool.connect();
  try{
   await db.query('BEGIN');await db.query('SELECT pg_advisory_xact_lock(21451,1)');
   await db.query('CREATE SCHEMA IF NOT EXISTS '+this.schema);
   await db.query(`CREATE OR REPLACE VIEW ${this.schema}.sqlite_master AS
    SELECT table_name AS name,'table'::text AS type FROM information_schema.tables WHERE table_schema=$1`
     .replace('$1',"'"+this.schema+"'"));
   await db.query('COMMIT');
  }catch(error){await db.query('ROLLBACK').catch(()=>{});throw error;}finally{db.release();}
 }
 async query(sql,args=[]){return (this.context.getStore()?.client||this.pool).query(sql,args);}
 async transaction(action){
  if(this.context.getStore())return action();
  const client=await this.pool.connect(),state={client,ddl:new Set(),responses:[]};
  try{
   await client.query('BEGIN');
   // Domain transactions are short and contain no external HTTP calls. A single
   // advisory lock preserves cross-process quota/ownership decisions atomically.
   await client.query('SELECT pg_advisory_xact_lock(21451,2)');
   const value=await this.context.run(state,action);await client.query('COMMIT');
   for(const sql of state.ddl)this.ddl.add(sql);
   for(const response of state.responses)response();
   return value;
  }catch(error){await client.query('ROLLBACK').catch(()=>{});throw error;}finally{client.release();}
 }
 afterCommit(action){const state=this.context.getStore();if(!state)return false;state.responses.push(action);return true;}
 prepare(input){
  const pragma=/^PRAGMA table_info\((\w+)\)$/.exec(input.trim());
  const sql=pragma?null:postgresSql(input);
  const execute=async(args,run=false)=>{
   if(pragma)return this.query('SELECT column_name AS name FROM information_schema.columns WHERE table_schema=$1 AND table_name=$2',[this.schema,pragma[1]]);
   const statement=run&&/^INSERT INTO robokassa_invoices\b/i.test(sql)&&!/\bRETURNING\b/i.test(sql)?sql+' RETURNING id':sql;
   return this.query(statement,args);
  };
  return {get:async(...args)=>(await execute(args)).rows[0],all:async(...args)=>(await execute(args)).rows,
   run:async(...args)=>{const result=await execute(args,true);return {changes:result.rowCount,lastInsertRowid:result.rows[0]?.id};}};
 }
 async exec(input){
  const sql=postgresSql(input).trim();if(!sql)return;
  if(/^(BEGIN|COMMIT|ROLLBACK)\b/i.test(sql))throw new Error('Use transaction() for PostgreSQL');
  const ddl=/^(CREATE|ALTER)\b/.test(sql);
  if(ddl&&(this.ddl.has(sql)||this.context.getStore()?.ddl.has(sql)))return;
  await this.query(sql);
  if(ddl)(this.context.getStore()?.ddl||this.ddl).add(sql);
 }
 async probe(){
  const marker=new Error('probe rollback');
  try{await this.transaction(async()=>{await this.query('CREATE TEMP TABLE IF NOT EXISTS readiness_probe(id INTEGER)');
   await this.query('INSERT INTO readiness_probe VALUES(1)');throw marker;});}
  catch(error){if(error===marker)return true;return false;}
  return false;
 }
 async close(){await this.pool.end();}
}
module.exports={PostgresDatabase,postgresSql};
